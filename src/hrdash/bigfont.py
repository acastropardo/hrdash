"""Numeros gigantes estilo bloque para la terminal (digitos 5x7 -> 10x4 celdas)."""

GLYPHS = {
    "0": ("01110", "10001", "10011", "10101", "11001", "10001", "01110"),
    "1": ("00100", "01100", "00100", "00100", "00100", "00100", "01110"),
    "2": ("01110", "10001", "00001", "00010", "00100", "01000", "11111"),
    "3": ("11110", "00001", "00001", "01110", "00001", "00001", "11110"),
    "4": ("00010", "00110", "01010", "10010", "11111", "00010", "00010"),
    "5": ("11111", "10000", "11110", "00001", "00001", "10001", "01110"),
    "6": ("01110", "10000", "10000", "11110", "10001", "10001", "01110"),
    "7": ("11111", "00001", "00010", "00100", "01000", "01000", "01000"),
    "8": ("01110", "10001", "10001", "01110", "10001", "10001", "01110"),
    "9": ("01110", "10001", "10001", "01111", "00001", "00010", "01110"),
    "-": ("00000", "00000", "00000", "11111", "00000", "00000", "00000"),
    "?": ("01110", "10001", "00001", "00010", "00100", "00000", "00100"),
    " ": ("00000", "00000", "00000", "00000", "00000", "00000", "00000"),
}

# (top, bottom) -> glifo de bloque
_PAIRS = {(1, 1): "██", (1, 0): "▀▀", (0, 1): "▄▄", (0, 0): "  "}
_PAIRS1 = {(1, 1): "█", (1, 0): "▀", (0, 1): "▄", (0, 0): " "}

# Corazones en pixel-art (ancho x alto), niveles 1..3
HEARTS = {
    1: [".##.##.",
        "#######",
        "#######",
        ".#####.",
        "..###..",
        "...#..."],
    2: [".##...##.",
        "#########",
        "#########",
        ".#######.",
        "..#####..",
        "...###...",
        "....#...."],
    3: ["..###...###..",
        ".#####.#####.",
        ".###########.",
        "#############",
        ".###########.",
        "..#########..",
        "...#######...",
        "....#####....",
        ".....###....."],
}


def render_heart(level: int) -> list[str]:
    """Corazon en 1-5 filas de terminal segun nivel (0..3). Nivel 0 = glifo ♥."""
    if level <= 0:
        return ["♥"]
    grid = HEARTS[min(level, 3)]
    w = len(grid[0])
    g = list(grid)
    if len(g) % 2:
        g.append("." * w)
    rows = []
    for p in range(0, len(g), 2):
        rows.append("".join(
            _PAIRS1[(1 if a == "#" else 0, 1 if b == "#" else 0)]
            for a, b in zip(g[p], g[p + 1])))
    return rows


def render_big(text: str) -> list[str]:
    """Devuelve 4 lineas de terminal que dibujan `text` en digitos gigantes."""
    out = [""] * 4
    for ch in text:
        glyph = GLYPHS.get(ch, GLYPHS["?"])
        for p in range(4):
            r_top, r_bot = p * 2, p * 2 + 1
            bottom = glyph[r_bot] if r_bot < 7 else "00000"
            cells = (_PAIRS[(1 if a == "1" else 0, 1 if b == "1" else 0)]
                     for a, b in zip(glyph[r_top], bottom))
            out[p] += "".join(cells) + " "
    return out
